export function cite(article: Article): string {
  if (article.id.startsWith('DEMO-')) return `[${article.id}]`;
  const code = article.code === 'constitution' ? 'Конституция РФ' : 'УК РФ';
  return `[${code} ст. ${article.article}]`;
}
